    await p.click('#f-pref label:has-text("Higher")');
    await p.click('#btn-rank');
    const ranks = [...new Set(await p.$$eval('#results tbody .rk', r => r.map(x => Number(x.textContent))))];
    check(ranks[0] === 1 && ranks.every((r, i) => r === i + 1), `ranks go 1, 2, 3 with no gaps (${ranks.slice(0, 4)})`);
    await p.click('#f-pref label:has-text("No preference")');
    await p.$eval('#weights input[data-group=factor][data-key=corner]', r => { r.value = '-3'; r.dispatchEvent(new Event('input')); });
    await p.$eval('#f-min', s => { s.value = s.options[s.options.length - 1].value; });
    await p.click('#btn-rank');
    check((await p.$$eval('#results tr.first-neg', r => r.length)) === 1 && (await p.$$eval('#results tr.neg-row', r => r.length)) > 0, 'line and shading between plus and minus scores');
    await p.$eval('#f-min', s => { s.value = s.options[0].value; });
    await p.click('#f-types label:has-text("2-Room Flexi")');
    await p.click('#btn-rank');
    await p.waitForFunction(() => document.querySelector('#result-count').textContent.startsWith('816'));
    check(true, '2-Room Flexi covers Type 1 and Type 2 (816 units)');
    const fac = await p.$$eval('#weights .meter-group', g => g.filter(x => /Facilities nearby/.test(x.textContent)).map(x => x.querySelectorAll('.meter').length));
    check(fac.length === 1 && fac[0] > 1, `one meter per facility type (${fac[0]})`);
    await p.selectOption('#project', 'sembawang-brook-6');
    await p.waitForFunction(() => document.querySelector('#result-count').textContent.startsWith('0'));
    check((await p.inputValue('#f-pref input:checked')) === 'higher', 'Higher is the default again for each project');
    const groupsOf = () => p.$$eval('#weights .meter-group', g => g.map(x => [x.querySelector('.eyebrow').textContent.replace(/\?$/, '').trim(), [...x.querySelectorAll('.meter label')].map(l => l.childNodes[0].textContent)]));
    const gs = await groupsOf();
    check(gs.map(g => g[0]).join('|') === 'Blocks|Sun direction|Wind direction|Distance|Others|Facilities nearby (within 30 m)', `importance groups in order (${gs.map(g => g[0]).join(' | ')})`);
    const gm = Object.fromEntries(gs);
    check(gm['Wind direction'].join('|') === 'Faces the prevailing wind (SE to E)|Not blocked from the wind', 'Wind direction group, directly below Sun direction');
    check(gm['Distance'].join('|') === ['More than 30 m from the nearest visible unit', '10 m away from rubbish chute', 'Within 100 m from MRT', 'Within 100 m from a multi-storey car park'].filter(l => gm['Distance'].includes(l)).join('|') && gm['Distance'].length >= 3, 'Distance group members');
    check(gm['Others'].join('|') === 'Corner unit|Access to roof', 'Others group members');
    check(await p.$eval('#weights .meter-group:last-child .help', b => b.dataset.legend === 'facilities'), 'Facilities nearby (within 30 m) keeps its ? help button');
    check(!/Unit & site/.test(await p.textContent('#weights')), 'Unit & site heading is gone');
    const newMeters = await p.$$eval('#weights .meter label', m => m.map(x => x.childNodes[0].textContent));
    check(['Faces the prevailing wind (SE to E)', 'Not blocked from the wind', 'Within 100 m from a multi-storey car park'].every(l => newMeters.includes(l)),
      'wind and multi-storey car park meters appear for a project that has them (Sembawang Brook)');
    // Fresh visit: Higher is selected, even if an older visit left another choice behind, and Higher puts the highest storey first.
    const floorCtx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await stubFirebase(floorCtx);
    const fp = await floorCtx.newPage();
    fp.on('pageerror', e => errors.push(e.message));
    await fp.goto(`${base}/rank`);
    await fp.waitForSelector('#floor-groups .fg-card');
    check((await fp.inputValue('#f-pref input:checked')) === 'higher', 'fresh visit: Prioritise floors shows Higher selected');
    await fp.evaluate(() => { const k = 'mybto:last:' + JSON.parse(localStorage.getItem('project')); localStorage.setItem(k, JSON.stringify({ flat_types: [], blocks: [], floor_pref: 'lower', weights: {} })); });
    await fp.reload();
    await fp.waitForSelector('#floor-groups .fg-card');
    check((await fp.inputValue('#f-pref input:checked')) === 'higher', 'an old saved Lower choice is not restored: still Higher');
    await fp.click('#btn-rank');
    await fp.waitForSelector('#results tbody .rk');
    const top = await fp.evaluate(async () => {
      const key = JSON.parse(localStorage.getItem('project'));
      const units = await (await fetch(`/data/units/${key}.json`)).json();
      const pick = Scoring.filterUnits(units, { blocks: [...document.querySelectorAll('#f-blocks input:checked')].map(i => i.value), flatTypes: [...new Set(units.map(u => u.flat_type))].filter(t => Scoring.housingOf(t) === document.querySelector('#f-types input:checked').value) });
      return { max: Math.max(...pick.map(u => u.storey)), shown: Number(document.querySelector('#results tbody .addr').textContent.match(/#(\d+)-/)[1]) };
    });
    check(top.shown === top.max, `Higher with all weights 0: top unit is on the highest storey (${top.shown} of ${top.max})`);
    await floorCtx.close();
    const brookMeters = await p.$$eval('#weights .meter label', m => m.map(x => x.childNodes[0].textContent));
    check(brookMeters.includes('Future amenities/facilities') && brookMeters.includes('Mini-mart'), 'Sembawang Brook shows Future amenities/facilities and Mini-mart meters (from the brochure)');
    await p.click('#btn-rank');
    await p.waitForSelector('#results tbody .rk');
    check((await p.$$eval('#results thead th', h => h.map(x => x.childNodes[0]?.textContent || ''))).includes('Future amenities/facilities'), 'Future amenities/facilities has a tick column');
    await p.selectOption('#project', 'berlayar-rise-7');
    await p.waitForFunction(() => document.querySelector('#result-count').textContent.startsWith('0'));
    await p.click('#f-types label:has-text("2-Room Flexi")');
    await p.click('[data-blocks=none]');
    await p.click('#f-blocks label:has-text("200B")');
    const meters = await p.$$eval('#weights .meter label', m => m.map(x => x.textContent));
    check(meters.includes('Block 200B') && !meters.includes('Block 200A'), 'only selected blocks get a meter');
    check(!meters.some(m => m.startsWith('Type 1')) && meters.some(m => m.startsWith('Type 2')), '2RF Type 1 meter hidden when block 200B has none');
    await p.click('#btn-rank');
    check(await p.$$eval('#results tbody .addr small', s => s.every(x => x.textContent === 'Blk 200B')), 'block filter applied');

    await p.click('.star >> nth=0'); await p.click('.star >> nth=1'); await p.click('.star >> nth=2');
    check((await p.textContent('#flag-count')) === '3', 'Shortlisted button counts three starred units');
    await p.waitForTimeout(2600);
    const starred = (await dump()).shortlists.filter(r => r.project === 'berlayar-rise-7');
    check(starred.length === 1 && starred[0].unit_ids.split(', ').length === 3, 'starring units sends a shortlist to the fake sheet (3 units, debounced into one send)');
    check((await p.getAttribute('#btn-shortlisted', 'target')) === '_blank', 'Shortlisted opens in a new tab');
    const [sl] = await Promise.all([ctx.waitForEvent('page'), p.click('#btn-shortlisted')]);
    await sl.waitForSelector('#flag-list li .addr');
    const first = await sl.textContent('#flag-list li:nth-child(1) .addr');
    await sl.click('#flag-list li:nth-child(2) [data-act=up]');
    check((await sl.textContent('#flag-list li:nth-child(2) .addr')) === first, 'shortlist reorders');
    await sl.waitForTimeout(2600);
    const shortlistOf = async () => (await dump()).shortlists.filter(r => r.project === 'berlayar-rise-7');
    const after = await shortlistOf();
    check(after[0].unit_ids !== starred[0].unit_ids && [...after[0].unit_ids.split(', ')].sort().join() === [...starred[0].unit_ids.split(', ')].sort().join(), 'the new order replaced the old one');
    check(after.length === 1 && after[0].user === (await dump()).rankings[0].user && after[0].unit_ids.split(', ').length === 3, 'reordering sent the shortlist: one row per user and project, 3 units');
    await sl.close();

    // ---- Shortlist: persistence, latest rank and "was", clear all, share link round trip.
    const KEY = 'berlayar-rise-7';
    const flagsLs = pg_ => pg_.evaluate(k => JSON.parse(localStorage.getItem(k)), `flags:${KEY}`);
    const savedOrder = await flagsLs(p);
    await p.reload();
    await p.waitForSelector('#floor-groups .fg-card');
    check((await p.textContent('#flag-count')) === '3', 'after reopening the rank page the Shortlisted count is still 3');
    check((await p.inputValue('#project')) === KEY && (await p.$$eval('#f-blocks input:checked', i => i.map(x => x.value))).join() === '200B' && /last settings/.test(await p.textContent('#save-msg')), 'rank page restores the project, blocks and filters of the last ranking');
    await p.click('#btn-rank');
    await p.waitForSelector('#results tbody .rk');
    const on1 = await p.$$eval('#results .star.on', b => b.map(x => x.dataset.id));
    check(on1.length === 3 && on1.every(id => savedOrder.includes(id)), 'the same units are starred after reopening the rank page');
    const sl2 = await ctx.newPage();
    sl2.on('pageerror', e => errors.push(e.message));
    await sl2.goto(`${base}/shortlist`);
    await sl2.waitForSelector('#flag-list li .addr');
    const idsOnPage = pg_ => pg_.$$eval('#flag-list li', l => l.map(x => x.dataset.id));
    check((await idsOnPage(sl2)).join() === savedOrder.join(), 'the shortlist page shows the same starred units in the same order after reopening');
    const meta1 = await sl2.$$eval('#flag-list .meta', m => m.map(x => x.textContent));
    check(meta1.every(t => /Rank \d+ · score [+-]?\d/.test(t) && !/was/.test(t)), `each shortlisted unit shows its rank and score under the latest ranking (${meta1[0].split(' · ').slice(-2).join(' · ')})`);
    check(/Rank and score are from your latest ranking \(2-Room Flexi, 1 of \d+ blocks/.test(await sl2.textContent('#rank-note')), 'the shortlist page says which parameters the ranking used');
    if (SHOTS) { await sl2.setViewportSize({ width: 390, height: 844 }); await sl2.screenshot({ path: `${SHOTS}/shortlist-rank-1.png`, fullPage: true }); await sl2.setViewportSize({ width: 1440, height: 1000 }); }
    // Change a parameter and rank again: the shortlist page shows the new rank and the old one.
    await p.click('#f-pref label:has-text("Lower")');
