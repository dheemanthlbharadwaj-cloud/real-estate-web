    await sl2.waitForTimeout(2600);
    const clearedRow = (await dump()).shortlists.filter(r => r.project === KEY);
    check(clearedRow.length === 1 && clearedRow[0].unit_ids === '', 'Clear all is synced to the Sheet like any shortlist change');
